MERMAID = re.compile(r'<pre class="mermaid"><code>(.*?)</code></pre>', re.S)
HEADING = re.compile(r"<h([23])\b([^>]*)>(.*?)</h\1>", re.S | re.I)
HEADING_ID = re.compile(r'\bid="([^"]*)"')
TAG = re.compile(r"<[^>]+>")
BODY = re.compile(r"<body([^>]*)>", re.I)
MAIN = re.compile(r"<main>(.*?)</main>", re.S)
# A chapter-table row: `| 22 | <a href="22_....html">LLM Providers</a> | ... |`
CHAPTER_ROW = re.compile(
    r"<tr>\s*<td[^>]*>\s*(\d+)\s*</td>\s*<td[^>]*>\s*"
    r'<a\s+href="([^"]+)"[^>]*>(.*?)</a>',
    re.S,
)

BACK_ICON = (
    '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" '
    'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">'
    '<path d="M15 5l-7 7 7 7"/></svg>'
)

ICON = (
    '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" '
    'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">'
    '<path d="M8 4H5v16h3"/><path d="M11 8h9M11 12h9M11 16h6"/></svg>'
)


class Chapter(NamedTuple):
    label: str
    href: str
    html_twin: bool


def pandoc(*args: str, stdin: str = "") -> str:
    try:
        finished = subprocess.run(
            ["pandoc", *args],
            input=stdin,
            capture_output=True,
            text=True,
            check=True,
        )
    except FileNotFoundError:
        sys.exit("pandoc not found; install it (brew install pandoc)")
    except subprocess.CalledProcessError as exc:
        sys.exit(f"pandoc failed:\n{exc.stderr.strip()}")
    return finished.stdout


def unwrap_mermaid(match: re.Match[str]) -> str:
    body = match.group(1).replace("&quot;", '"').replace("&#39;", "'")
    return f'<pre class="mermaid">{body}</pre>'


def shell(title: str, inner: str, toc: bool = True) -> str:
    """A fresh house page around `inner` (fragment mode)."""
    with tempfile.TemporaryDirectory() as tmp:
        head = pathlib.Path(tmp) / "head.html"
        head.write_text(HEAD + (TOC_HEAD if toc else ""), encoding="utf-8")
        document = pandoc(
            "-f",
            "gfm",
            "-t",
            "html5",
            "-s",
            "--syntax-highlighting=none",
            "--metadata",
            f"pagetitle={title}",
            "-H",
            str(head),
        ).replace("</body>", inner + "\n</body>")
    return MERMAID.sub(unwrap_mermaid, document)


def collect_sections(body: str) -> list[tuple[int, str, str]]:
    """`(level, id, text)` for every h2/h3 the page can jump to."""
    sections: list[tuple[int, str, str]] = []
    for match in HEADING.finditer(body):
        id_match = HEADING_ID.search(match.group(2))
        if not id_match:
            continue
        text = html.unescape(TAG.sub("", match.group(3)))
        text = re.sub(r"\s+", " ", text).strip()
        if not text or text == "目录":
            continue
        sections.append((int(match.group(1)), id_match.group(1), text))
    return sections


def collect_chapters(page: pathlib.Path) -> list[Chapter]:
    """Chapter-table rows of the index page, as sidebar entries.

    The table is already HTML with `.html` targets, so the rows are read back
    verbatim; a row whose target is missing on disk is still listed, but muted.
    """
    chapters: list[Chapter] = []
    for number, href, title in CHAPTER_ROW.findall(page.read_text(encoding="utf-8")):
        label = re.sub(r"\s+", " ", html.unescape(TAG.sub("", title))).strip()
        target = page.parent / pathlib.PurePosixPath(href).name
        chapters.append(
            Chapter(
                label=f"{number}. {label}",
                href=href,
                html_twin=target.is_file(),
            )
        )
    return chapters


def section_item(level: int, section_id: str, text: str) -> str:
    href = "#" + quote(section_id, safe="")
    title = html.escape(text, quote=True)
    return (
        f'<li class="toc-l{level}"><a href="{href}" title="{title}">'
        f'<span class="toc-label">{html.escape(text)}</span></a></li>'
    )


def chapter_item(chapter: Chapter) -> str:
    label = html.escape(chapter.label)
    href = html.escape(chapter.href, quote=True)
    if chapter.html_twin:
        return (
            f'<li class="toc-l2"><a href="{href}">'
            f'<span class="toc-label">{label}</span></a></li>'
        )
    # No HTML twin yet: link the Markdown source (as the chapter table does) and
    # keep it muted so the reader can tell it opens a raw `.md`, not a styled page.
    title = html.escape(f"{chapter.label}（Markdown 源文件，尚无 HTML 版）", quote=True)
    return (
        f'<li class="toc-l2 is-source">'
        f'<a href="{href}" title="{title}"><span class="toc-label">{label}</span></a></li>'
    )


def build_nav(
    sections: list[tuple[int, str, str]],
    chapters: list[Chapter],
    home: str | None,
) -> str:
    parts = [
        '<nav class="book-toc" id="book-toc" aria-label="目录">',
        '<div class="toc-card">',
        f'<span class="toc-icon">{ICON}</span>',
        '<span class="toc-title">目录</span>',
    ]
    if home:
        parts.append(
            f'<a class="toc-index" href="{home}" title="返回全书总目录">'
            f'{BACK_ICON}<span>总目录</span></a>'
        )
    parts.append(
        '<button class="toc-collapse" type="button" aria-expanded="true">收起</button>'
    )
    parts.append("</div>")
    if chapters:
        parts.append('<div class="toc-group">')
        if sections:
            parts.append('<p class="toc-group-label">章节</p>')
        parts.append('<ol class="toc-list">')
        parts.extend(chapter_item(chapter) for chapter in chapters)
        parts.extend(["</ol>", "</div>"])
    if sections:
        parts.append('<div class="toc-group">')
        if chapters:
            parts.append('<p class="toc-group-label">本页</p>')
        parts.append('<ol class="toc-list">')
        parts.extend(section_item(*section) for section in sections)
        parts.extend(["</ol>", "</div>"])
    parts.append("</nav>")
    return "\n".join(parts)


