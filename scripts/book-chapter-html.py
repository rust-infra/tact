#!/usr/bin/env python3
"""Wrap an HTML fragment in the house page shell, or refresh a book page.

`book/*.html` is the source of truth: chapters are edited as HTML, not rendered
from Markdown. What this script owns is the shell around that content — the
house stylesheet, the mermaid initializer, and the sticky sidebar directory.
Two modes:

    # Rebuild the sidebar of an existing book page from its own headings and
    # chapter table; the <main> content is preserved byte for byte:
    python3 scripts/book-chapter-html.py --refresh book/22_chapter_llm_zh.html

    python3 scripts/book-chapter-html.py --refresh book/*.html
    python3 scripts/book-check.py book        # links + anchors + sidebar coverage

    # Splice a fragment into the same shell (docs/design pages):
    python3 scripts/book-chapter-html.py docs/design/x.fragment.html \
        docs/design/x.html --title "..."

A fragment has no Markdown to convert: it borrows pandoc's empty page so both
modes share one shell, then is spliced in as-is.

What the shell adds:

* The house stylesheet and the mermaid initializer declared below, so every
  page is styled the same way.
* A sticky sidebar directory built from the page's own `h2`/`h3` ids (plus,
  for `index_zh.html`, its chapter table) with the body wrapped in `<main>`.
  `--toc` picks the mode; `auto` gives chapters + page sections to the book
  index, sections to any other page, and nothing to fragments.
* Mermaid fences in a fragment are rewritten to `<pre class="mermaid">TEXT</pre>`.
  Pandoc emits `<pre class="mermaid"><code>TEXT</code></pre>`, and the extra
  `<code>` node only sits between mermaid and the diagram source it reads.
"""

