#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_desktop_string_has_a_chinese_translation() {
        for &key in ALL {
            if matches!(key, TextKey::Application | TextKey::Mcp) {
                continue;
            }
            assert_ne!(
                text(CatalogLocale::En, key),
                text(CatalogLocale::Zh, key),
                "{key:?}"
            );
        }
    }

    #[test]
    fn desktop_root_uses_the_message_catalog_for_owned_surfaces() {
        let root = include_str!("root.rs");
        for hard_coded in [
            ".placeholder(\"Search sessions by title or id\")",
            ".aria_label(\"Tact Desktop title bar\")",
            ".aria_label(\"Projects and sessions\")",
            ".aria_label(\"Run inspector\")",
            ".aria_label(\"Session Manager\")",
            ".child(\"Session Manager\")",
            ".child(\"Create Goal\")",
            ".child(\"Confirm\")",
            ".child(\"Authorize\")",
            ".child(\"Remove\")",
            ".child(\"Logout\")",
            ".child(\"Manage\")",
            ".child(\"Disable\")",
            ".child(\"Enable\")",
            ".child(\"Phase\")",
            ".child(\"Turns\")",
            ".child(\"Tokens\")",
        ] {
            assert!(
                !root.contains(hard_coded),
                "hard-coded UI string: {hard_coded}"
            );
        }
        assert!(root.contains("TextKey::SearchSessions"));
        assert!(root.contains("TextKey::SessionManager"));
    }
}
